// Define o pacote onde a enumeração Habilidade está localizada
package enumeradores

// Cria uma enumeração chamada Habilidade.
// Ela representa as diferentes habilidades disponíveis.
enum class Habilidade {

    // Representa a habilidade de instalação
    INSTALACAO,

    // Representa a habilidade na área financeira
    FINANCEIRO,

    // Representa a habilidade na área administrativa
    ADMINISTRATIVO,

    // Representa a habilidade na área de logística
    LOGISTICA
}