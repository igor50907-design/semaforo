// Define o pacote onde a classe Material está localizada
package enumeradores

// Cria uma enumeração chamada Material.
// Ela representa os tipos de materiais disponíveis.
enum class Material {

    // Representa o material polietileno
    POLIETILENO,

    // Representa o material fibra de vidro
    FIBRA_DE_VIDRO,

    // Representa o material inox (aço inoxidável)
    INOX
}