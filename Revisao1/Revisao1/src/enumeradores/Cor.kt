// Define o pacote onde a classe Cor está localizada
package enumeradores

// Cria uma enumeração chamada Cor.
// Ela representa as opções de cores disponíveis.
enum class Cor {

    // Representa a cor azul forte
    AZUL_FORTE,

    // Representa a cor azul fraco
    AZUL_FRACO,

    // Representa a cor branca
    BRANCO,

    // Representa a cor cinza
    CINZA
}